# Virtual TVET - catalog builder
# Scans the Basic, Common and Core folders next to this Virtual-TVET folder
# and rewrites catalog.js so the campus shows every CBLM you add.
# Run it by double-clicking "Update Catalog.bat".
# Developed by LEONIL RYAN L. DELA PENA, Senior TESD Specialist, RTC-Cebu

$here   = Split-Path -Parent $MyInvocation.MyCommand.Path
$root   = Split-Path -Parent $here
$out    = Join-Path $here "catalog.js"

# Official unit titles (add new codes here when you add new qualifications)
$titles = @{
  "400311319"="Lead Workplace Communication";
  "400311320"="Lead Small Teams";
  "400311321"="Apply Critical Thinking and Problem-Solving Techniques in the Workplace";
  "400311322"="Work in a Diverse Environment";
  "400311323"="Propose Methods of Applying Learning and Innovation in the Organization";
  "400311324"="Use Information Systematically";
  "400311325"="Evaluate Occupational Safety and Health Work Practices";
  "400311326"="Evaluate Environmental Work Practices";
  "400311327"="Facilitate Entrepreneurial Skills for Micro-Small-Medium Enterprises (MSMEs)";
  "ELC311201"="Perform Mensuration and Calculation";
  "ELC311202"="Prepare and Interpret Technical Drawing";
  "ELC311204"="Apply Quality Standards";
  "ELC311205"="Use Hand Tools";
  "ELC311206"="Terminate and Connect Electrical Wiring and Electronic Circuits";
  "ELC311212"="Maintain Tools and Equipment";
  "ELC741304"="Perform Roughing-in and Wiring Activities for Three-Phase Distribution System for Power, Lighting and Motor Control Panel";
  "ELC741305"="Perform Installation of Data Measurement and Control System on Electrical and Auxiliary Equipment";
  "ELC741306"="Install, Assemble, Test and Maintain Motor Control System"
}

function JsStr([string]$s){ return '"' + ($s -replace '\\','\\' -replace '"','\"') + '"' }

$items = @()
foreach($cat in @("Basic","Common","Core")){
  $dir = Join-Path $root $cat
  if(-not (Test-Path $dir)){ continue }
  Get-ChildItem -Path $dir -File | Where-Object { $_.Extension -match '^\.(docx|doc|pdf|pptx)$' -and $_.Name -notlike '~$*' } | Sort-Object Name | ForEach-Object {
    $name = $_.BaseName
    $code = ""; $title = $name
    # Expected pattern: CBLM_EIM-NCIII_<CODE>_<TitleInCamelCase>_Rev00
    $parts = $name -split '_'
    if($parts.Count -ge 4){
      $code = $parts[2]
      if($titles.ContainsKey($code)){ $title = $titles[$code] }
      else { $title = ($parts[3] -creplace '([a-z])([A-Z])','$1 $2') }
    }
    $size = [math]::Round($_.Length / 1MB, 1)
    $file = "../$cat/" + $_.Name
    $items += "    {""category"":""$cat"",""code"":$(JsStr $code),""title"":$(JsStr $title),""file"":$(JsStr $file),""sizeMB"":$size}"
  }
}

$today = Get-Date -Format "yyyy-MM-dd"
$js = @"
// Virtual TVET - content catalog (auto-generated by build-catalog.ps1)
// File paths are relative to this Virtual-TVET folder.
window.VTVET_CATALOG = {
  "qualification": "Electrical Installation and Maintenance NC III",
  "short": "EIM NC III",
  "institution": "TESDA Regional Training Center - Cebu",
  "generated": "$today",
  "units": [
$($items -join ",`r`n")
  ],
  "lms": []
};
"@

[System.IO.File]::WriteAllText($out, $js, (New-Object System.Text.UTF8Encoding($false)))
Write-Host "catalog.js updated: $($items.Count) CBLMs found." -ForegroundColor Green
